param(
  [string]$Root = (Split-Path $PSScriptRoot -Parent),   # the merchant-portal-workflows folder
  [string]$Out = ''                                     # default: dist\merchant-portal-workflows.html
)
<#
  Packs the viewer (index.html, viewer/, src/) into ONE self-contained HTML file: styles, scripts, data and images inline.
  The file opens offline in any browser, can be emailed, put on Drive, or added to a Claude project as a document.
  Only the fonts still come from Google Fonts; without a connection the page falls back to the system font.
  Called by build-docs.ps1; can also be run on its own.
#>
$ErrorActionPreference = 'Stop'
if (-not $Out) { $Out = Join-Path $Root 'dist\merchant-portal-workflows.html' }
$utf8 = New-Object System.Text.UTF8Encoding($false)
$read = { param($rel) [IO.File]::ReadAllText((Join-Path $Root $rel), $utf8) }
$png = { param($rel) 'data:image/png;base64,' + [Convert]::ToBase64String([IO.File]::ReadAllBytes((Join-Path $Root $rel))) }

$html = & $read 'index.html'
foreach ($css in @('viewer/base.css', 'viewer/viewer.css')) {
  $html = $html.Replace('<link rel="stylesheet" href="' + $css + '">', "<style>`n" + (& $read $css) + "`n</style>")
}
foreach ($js in @('src/model.js', 'src/workflows.js', 'viewer/viewer.js')) {
  $code = & $read $js
  if ($code -match '</script') { throw "$js contains </script and cannot be inlined." }
  $html = $html.Replace('<script src="' + $js + '"></script>', "<script>`n" + $code + "`n</script>")
}
foreach ($img in @('viewer/paytinno-icon.png', 'viewer/paytinno-mark.png')) { $html = $html.Replace('"' + $img + '"', '"' + (& $png $img) + '"') }
if ($html -match '(src|href)="(viewer|src)/') { throw 'A local reference was left in the page.' }

$stamp = (Get-Date).ToString('yyyy-MM-dd HH:mm')
$html = $html.Replace('<title>Merchant Portal Workflows</title>', "<title>Merchant Portal Workflows</title>`n<!-- Single-file build of merchant-portal-workflows, $stamp. Generated by tools/build-html.ps1 from src/; do not edit. -->")
New-Item -ItemType Directory -Force (Split-Path $Out -Parent) | Out-Null
[IO.File]::WriteAllText($Out, ($html -replace "`r`n", "`n"), $utf8)
Write-Output ("Wrote {0} ({1:N0} KB)" -f $Out, ((Get-Item $Out).Length / 1KB))
